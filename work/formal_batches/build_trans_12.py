def marker_sequence(text: str) -> list[str]:
    return re.findall(
        r"\{(?:SPEAKER_[^}]+|PART_\d+|SIG_[^}]+|PLAYER_NAME|DYN_\d+)\}"
        r"|\$anim[A-Za-z]\d+|<[^>]+>|\*",
        text,
    )


