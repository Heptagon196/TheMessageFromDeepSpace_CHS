def main() -> None:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    if len(sys.argv) == 3 and sys.argv[1] == "--show":
        start, end = map(int, sys.argv[2].split(":"))
        for i, item in enumerate(source[start:end], start):
            print(f"{i}\t{item['text_index']}\t{item['context'].get('chunk_id')}\t{item['source_text']}")
        return

    if len(TRANSLATIONS) != len(source):
        raise SystemExit(f"translation count mismatch: {len(TRANSLATIONS)} != {len(source)}")
    output = [
        {"text_index": item["text_index"], "translated_text": translated}
        for item, translated in zip(source, TRANSLATIONS, strict=True)
    ]
    OUTPUT.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    NEWTERMS.write_text("", encoding="utf-8")
    print(f"wrote {len(output)} translations")


if __name__ == "__main__":
    main()
