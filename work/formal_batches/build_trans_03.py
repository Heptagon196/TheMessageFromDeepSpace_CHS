def main() -> None:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    if len(translations) != len(source):
        raise SystemExit(f"translation count {len(translations)} != source count {len(source)}")
    result = [
        {
            "text_index": item["text_index"],
            "translated_text": polish_overrides.get(item["text_index"], translated),
        }
        for item, translated in zip(source, translations, strict=True)
    ]
    unknown = set(polish_overrides) - {item["text_index"] for item in source}
    if unknown:
        raise SystemExit(f"polish override index not in source: {sorted(unknown)}")
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(result)} translations -> {OUTPUT}")


if __name__ == "__main__":
    main()
