def main() -> None:
    source_items = json.loads(SOURCE.read_text(encoding="utf-8"))
    translations = TRANSLATIONS.copy()
    for index, translated in POLISH_OVERRIDES.items():
        translations[index] = translated

    if len(source_items) != len(translations):
        raise SystemExit(
            f"translation count mismatch: {len(translations)} != {len(source_items)}"
        )

    output_items = [
        {"text_index": item["text_index"], "translated_text": translated}
        for item, translated in zip(source_items, translations, strict=True)
    ]
    OUTPUT.write_text(
        json.dumps(output_items, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(output_items)} translations -> {OUTPUT}")


if __name__ == "__main__":
    main()
