def main() -> None:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    if len(source) != len(translations):
        raise RuntimeError(
            f"translation count mismatch: source={len(source)}, translations={len(translations)}"
        )

    seen: dict[str, str] = {}
    output = []
    for item, translated_text in zip(source, translations, strict=True):
        source_text = item["source_text"]
        previous = seen.setdefault(source_text, translated_text)
        if previous != translated_text:
            raise RuntimeError(
                f"inconsistent translation for {source_text!r}: {previous!r} != {translated_text!r}"
            )
        output.append(
            {
                "text_index": item["text_index"],
                "translated_text": translated_text,
            }
        )

    OUTPUT.write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
